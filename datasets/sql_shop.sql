CREATE TABLE users (
  user_id     INTEGER PRIMARY KEY, -- 고객 번호
  signup_date TEXT,                -- 가입일 (YYYY-MM-DD)
  channel     TEXT,                -- 가입 경로: 검색 · SNS · 추천
