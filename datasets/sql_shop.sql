CREATE TABLE orders (
  order_id   INTEGER PRIMARY KEY,  -- 주문 번호
  user_id    INTEGER,              -- 고객 번호 (users.user_id)
  order_date TEXT,                 -- 주문일 (YYYY-MM-DD)
  category   TEXT,                 -- 상품 분류
